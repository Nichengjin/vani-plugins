export function resolveLocale(locale) {
  if (!locale) return 'en'
  if (/^zh/iu.test(locale)) return /TW|HK|MO|Hant/iu.test(locale) ? 'zh-TW' : 'zh-CN'
  const base = locale.split('-')[0]?.toLowerCase()
  if (base === 'ja' || base === 'fr') return base
  return 'en'
}
